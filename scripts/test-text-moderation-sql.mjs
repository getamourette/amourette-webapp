import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';
import { seedPair, token, command } from './like-test-database.mjs';
import { asUser } from './name-test-database.mjs';
import { installTextModerationSchema } from './text-moderation-test-database.mjs';

const db = new PGlite();
const adapter = { query: (sql,args) => args ? db.query(sql,args) : db.exec(sql).then(results=>results.at(-1)) };
try {
  await installTextModerationSchema(adapter);
  const {a,b,c,venue,night} = await seedPair(adapter);
  const other = await seedPair(adapter);
  await db.query('insert into admins values($1)',[other.a]);
  const admin = (sql,args=[]) => asUser(db,other.a,sql,args);
  const state = async (actor=a) => asUser(db,actor,'select * from my_text_corrections()');
  const review = async (field,profile=a,scope=night) => (await admin('select * from admin_text_reviews($1,$2)',[profile,scope])).find(r=>r.field===field);
  const require = async (field,profile=a,scope=night,revision) => admin('select require_profile_text_correction($1,$2,$3,$4,$5)',[profile,field,revision ?? (await review(field,profile,scope)).revision,'inappropriate',scope]);
  const submitBio = async (value,actor=a,id=crypto.randomUUID()) => {
    const s=(await state(actor)).find(r=>r.field==='bio');
    await asUser(db,actor,'select submit_bio_correction($1,$2,$3)',[id,value,s.revision]); return id;
  };
  const decideBio = (id,action='approved') => admin('select * from decide_bio_correction($1,$2)',[id,action]);
  const submitName = async (value,actor=a,id=crypto.randomUUID()) => {
    await asUser(db,actor,'select submit_name_correction($1,$2)',[id,value]); return id;
  };
  const decideName = (id,action='approved') => admin('select * from decide_name_correction($1,$2)',[id,action]);
  const profile = async () => (await db.query('select first_name,bio from profiles where id=$1',[a])).rows[0];
  const required = async field => (await state()).find(r=>r.field===field).required;
  const receipts = async () => (await db.query('select topic,payload from realtime.messages order by topic')).rows;
  await assert.rejects(asUser(db,a,'select * from admin_text_reviews()'),/not authorized/);
  assert.deepEqual(await admin('select * from admin_text_reviews($1)',[a]),[],'no arbitrary founder browsing');
  const initialRevision=(await review('bio')).revision;
  await assert.rejects(require('bio',a,other.night,initialRevision),/not authorized/);
  await assert.rejects(asUser(db,a,'select require_profile_text_correction($1,$2,$3,$4,$5)',[a,'bio',initialRevision,'inappropriate',night]),/not authorized/);
  await assert.rejects(asUser(db,b,'select * from admin_text_history($1,$2)',[a,night]),/not authorized/);
  await assert.rejects(asUser(db,a,"update private.profile_text_events set action='approved'"),/permission denied/);
  await assert.rejects(asUser(db,a,'select * from private.profile_text_state'),/permission denied/);
  await assert.rejects(asUser(db,a,'select * from private.profile_text_events'),/permission denied/);
  await assert.rejects(asUser(db,a,'select * from private.bio_corrections'),/permission denied/);
  await assert.rejects(asUser(db,a,'select private.apply_name_correction($1,$2)',[crypto.randomUUID(),'approved']),/permission denied/);
  await assert.rejects(asUser(db,null,'select * from my_text_corrections()'),/authentication required/);
  const missingName=crypto.randomUUID();
  await db.query('insert into auth.users values($1)',[missingName]);
  await assert.rejects(db.query("insert into profiles(id,first_name,gender,interested_in) values($1,null,'woman',array['woman'])",[missingName]),/first name required/);
  await db.exec('set role anon');
  await assert.rejects(db.query('select * from my_text_corrections()'),/permission denied/);
  await db.exec('reset role');
  // Existing ordinary bio edits and voluntary name requests keep their semantics.
  await asUser(db,a,"update profiles set bio='Published bio' where id=$1",[a]);
  const voluntary=await submitName('Voluntary');
  assert.equal((await profile()).first_name,'Test');
  await command(adapter,{actor:a,target:b,night,token:await token(adapter,a,venue,b)});
  const matched=await command(adapter,{actor:b,target:a,night,token:await token(adapter,b,venue,a)});
  const match=matched.match_id;
  assert.ok(match);
  const staleBio=await review('bio');
  await asUser(db,a,"update profiles set bio='Newer bio' where id=$1",[a]);
  await assert.rejects(require('bio',a,night,staleBio.revision),/review changed/);
  const eventCount=async()=>Number((await db.query('select count(*) n from private.profile_text_events')).rows[0].n);
  assert.equal(await eventCount(),0,'failed action leaves no audit event');
  const inspected=await review('bio');
  for(const [field,reason,revision] of [[null,'inappropriate',inspected.revision],['gender','inappropriate',inspected.revision],['bio',null,inspected.revision],['bio','unknown',inspected.revision],['bio','inappropriate',null]]) {
    await assert.rejects(admin('select require_profile_text_correction($1,$2,$3,$4,$5)',[a,field,revision,reason,night]));
  }
  assert.equal(await eventCount(),0);
  await db.exec('truncate realtime.messages');
  await require('bio');
  assert.deepEqual(await profile(),{first_name:'Test',bio:null});
  assert.ok(await token(adapter,b,venue,a),'bio rejection preserves discovery');
  assert.equal((await asUser(db,b,'select * from chat_partner_state($1)',[match]))[0].bio,null);
  assert.equal((await asUser(db,b,'select bio from profiles where id=$1',[a]))[0].bio,null,'direct read is redacted');
  assert.deepEqual((await receipts()).map(r=>r.topic),[a,b,c].sort().map(id=>`participant:${id}`));
  for(const r of await receipts()) assert.deepEqual(Object.keys(r.payload).sort(),['id','version']);
  await assert.rejects(asUser(db,a,"update profiles set bio='Bypass' where id=$1",[a]),/approval required/);
  await assert.rejects(db.query("update profiles set bio='Privileged bypass' where id=$1",[a]),/approval required/);
  for(const value of ['x'.repeat(301),'😀'.repeat(301),' '.repeat(16385)]) await assert.rejects(submitBio(value));
  const bio=await submitBio('  '+ '😀'.repeat(300)+'  ');
  await assert.rejects(submitBio('Second'),/pending correction exists/);
  await assert.rejects(asUser(db,b,'select cancel_bio_correction($1)',[bio]),/not authorized/);
  await assert.rejects(asUser(db,a,'select * from decide_bio_correction($1,$2)',[bio,'approved']),/not authorized/);
  assert.equal((await profile()).bio,null,'pending text is private');
  await decideBio(bio,'rejected');
  assert.equal(await required('bio'),true);
  assert.deepEqual(await decideBio(bio),[{applied:false,status:'rejected'}],'old approval cannot overwrite rejection');
  const cancelled=await submitBio('Cancelled');
  await asUser(db,a,'select cancel_bio_correction($1)',[cancelled]);
  const replacement=await submitBio('Approved bio');
  assert.deepEqual(await decideBio(cancelled),[{applied:false,status:'cancelled'}]);
  await require('first_name');
  assert.equal((await profile()).first_name,null);
  assert.equal(await token(adapter,b,venue,a),undefined);
  assert.equal(await token(adapter,a,venue,c),undefined);
  assert.equal((await asUser(db,b,'select * from chat_partner_state($1)',[match]))[0].first_name,null);
  assert.equal((await asUser(db,b,'select first_name from profiles where id=$1',[a]))[0].first_name,null);
  assert.deepEqual(await decideName(voluntary),[{applied:false,status:'cancelled'}]);
  assert.equal(await required('first_name'),true);
  await decideBio(replacement);
  assert.equal((await profile()).bio,'Approved bio');
  assert.equal(await required('bio'),false);
  assert.equal(await required('first_name'),true,'bio approval cannot clear name');
  await asUser(db,a,"update profiles set bio='Normal again' where id=$1",[a]);
  const refused=await submitName('Refused');
  await decideName(refused,'rejected');
  assert.equal((await profile()).first_name,null);
  const name=await submitName('Corrected');
  await db.query("insert into venue_ejections(profile_id,venue_night_id) values($1,$2)",[a,night]);
  await db.query('update photo_state set correction_required=true where profile_id=$1',[a]);
  await decideName(name);
  assert.deepEqual(await profile(),{first_name:'Corrected',bio:'Normal again'});
  assert.equal(await required('first_name'),false);
  assert.equal(await token(adapter,b,venue,a),undefined,'approval cannot clear night/photo restrictions');
  const partner=(await asUser(db,b,'select * from chat_partner_state($1)',[match]))[0];
  assert.equal(partner.first_name,'Corrected'); assert.equal(partner.correction_id,name);
  assert.equal(partner.seen_correction_id,null);
  assert.equal((await db.query('select count(*)::int n from matches where id=$1',[match])).rows[0].n,1);
  assert.equal((await db.query('select count(*)::int n from private.profile_edit_state where profile_id=$1',[a])).rows[0].n,0,'no preference allowance consumed');
  await assert.rejects(asUser(db,a,"update profiles set first_name='Bypass' where id=$1",[a]),/permission denied/);
  const history=await admin('select * from admin_text_history($1,$2)',[a,night]);
  assert.ok(history.some(e=>e.action==='required' && e.actor_id===other.a));
  assert.ok(history.some(e=>e.action==='approved' && e.request_id===name));
  assert.ok(history.every(e=>!('proposed_text' in e) && !('rejected_text' in e)));
  assert.ok((await state()).every(s=>!('actor_id' in s) && !('report_id' in s)));
  // Empty bio is an ordinary correction proposal requiring the same human review.
  await require('bio'); const empty=await submitBio('   ');
  assert.equal(await required('bio'),true); await decideBio(empty); assert.equal(await required('bio'),false);
  assert.equal((await profile()).bio,null);
  assert.equal((await db.query('select rejected_text from private.profile_text_state where profile_id=$1 and field=$2',[a,'bio'])).rows[0].rejected_text,null);
  const report=crypto.randomUUID();
  await db.query('insert into reports(id,reported_id) values($1,$2)',[report,other.b]);
  const reportRows=await admin('select * from admin_text_reviews($1,null,$2)',[other.b,report]);
  assert.equal(reportRows.length,2,'historical report context authorizes only its target');
  assert.deepEqual(await admin('select * from admin_text_reviews($1,null,$2)',[a,report]),[]);
  console.log('Text moderation: publication, grants, exact approvals, independent restrictions, private refresh and audit passed.');
} finally { await db.close(); }
