import { spawn } from 'node:child_process';
import { mkdir, readFile, rmdir, unlink, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const routes = [
  { directory: join(root, 'app/admin/profile-review-layout'), fixture: 'profile-review-preview' },
  { directory: join(root, 'app/profile/review-layout'), fixture: 'profile-correction-preview' },
];
const owned = [];
const typePaths = ['.next/dev/types/routes.d.ts', '.next/dev/types/validator.ts', 'next-env.d.ts'];
const previousTypes = [];
let child;
const stop = signal => child?.kill(signal);
const interrupt = () => stop('SIGINT');
const terminate = () => stop('SIGTERM');

try {
  for (const path of typePaths) {
    let source;
    try { source = await readFile(join(root, path), 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    previousTypes.push({ path: join(root, path), source });
  }
  for (const route of routes) {
    // Never replace a real route or another running preview's files.
    await mkdir(route.directory);
    const source = `// Generated by preview-profile-review.mjs; development-only fixtures.\nimport { notFound } from 'next/navigation';\nimport Fixture from '@/tests/helpers/${route.fixture}';\nexport default function Preview() {\n  if (process.env.NODE_ENV !== 'development') notFound();\n  return <Fixture />;\n}\n`;
    owned.push({ directory: route.directory, source });
    await writeFile(join(route.directory, 'page.tsx'), source, { flag: 'wx' });
  }
  child = spawn(process.execPath, [join(root, 'node_modules/next/dist/bin/next'), 'dev', '--hostname', '127.0.0.1', '--port', '3101'], {
    cwd: root, stdio: 'inherit', env: {
      ...process.env, NEXT_PUBLIC_SUPABASE_URL: 'http://127.0.0.1:54321',
      NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: 'profile-review-layout-fixture',
      SUPABASE_SERVICE_ROLE_KEY: '',
      PROFILE_PHOTO_REVIEW_ENABLED: 'false', EMAIL_DELIVERY_ENABLED: 'false',
      OPENAI_API_KEY: '', RESEND_API_KEY: '',
    },
  });
  process.on('SIGINT', interrupt);
  process.on('SIGTERM', terminate);
  const code = await new Promise((resolve, reject) => {
    child.once('error', reject);
    child.once('exit', code => resolve(code));
  });
  process.exitCode = code ?? 0;
} finally {
  process.removeListener('SIGINT', interrupt);
  process.removeListener('SIGTERM', terminate);
  for (const route of owned.reverse()) {
    const path = join(route.directory, 'page.tsx');
    let source;
    try { source = await readFile(path, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (source !== undefined && source !== route.source) throw new Error(`Preserving changed preview route: ${path}`);
    if (source !== undefined) await unlink(path);
    await rmdir(route.directory);
  }
  // Next dev generates validators for the temporary routes. Restore the
  // pre-preview generated types so a later standalone tsc does not import pages
  // that no longer exist. Production build types are never touched.
  if (child) for (const file of previousTypes) {
    if (file.source !== undefined) await writeFile(file.path, file.source);
    else try { await unlink(file.path); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
}
